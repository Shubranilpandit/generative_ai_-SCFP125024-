class CustomizedChatbot:
    """
    A persona-conditioned chatbot maintaining conversational history with a pinned system prompt.
    """
    def __init__(self, system_prompt: str = DEFAULT_TUTOR_SYSTEM_PROMPT,
                 backend: str = "api", model_name: str = "qwen/qwen3.8-27b"):
        self.system_prompt = system_prompt
        self.backend = backend
        self.model_name = model_name
        self.conversation_history: List[Dict[str, str]] = []
        self.api_client: Optional[Groq] = None
        self.ollama_endpoint = os.getenv("OLLAMA_HOST", "http://127.0.0.1:11434") + "/api/chat"

        # Initialize conversation with pinned system prompt
        self.reset_session()

        if backend == "api":
            api_key = load_api_key()
            if api_key and GROQ_AVAILABLE:
                self.api_client = Groq(api_key=api_key)
            else:
                self.backend = "ollama"
                self.model_name = "qwen3:4b"

    def reset_session(self) -> None:
        """Resets conversation history while preserving the pinned system instruction."""
        self.conversation_history = [
            {"role": "system", "content": self.system_prompt}
        ]

    def set_persona(self, new_system_prompt: str) -> None:
        """Updates the persona and resets history."""
        self.system_prompt = new_system_prompt
        self.reset_session()

    def send_message(self, user_text: str) -> str:
        """Dispatches message with full context including the system instruction."""
        self.conversation_history.append({"role": "user", "content": user_text})

        reply_text = ""
        try:
            if self.backend == "api" and self.api_client is not None:
                response = self.api_client.chat.completions.create(
                    model=self.model_name,
                    messages=self.conversation_history,
                    temperature=0.7,
                    max_tokens=250
                )
                reply_text = response.choices[0].message.content.strip()
            else:
                payload = {
                    "model": self.model_name,
                    "messages": self.conversation_history,
                    "stream": False,
                    "options": {"num_predict": 180}
                }
                res = requests.post(self.ollama_endpoint, json=payload, timeout=60)
                if res.status_code == 200:
                    reply_text = res.json().get("message", {}).get("content", "").strip()
                else:
                    reply_text = f"[Ollama Error {res.status_code}]"

        except Exception as exc:
            reply_text = f"[Error generating response: {exc}]"

        clean_reply = sanitize_for_console(reply_text)
        self.conversation_history.append({"role": "assistant", "content": clean_reply})
        return clean_reply


